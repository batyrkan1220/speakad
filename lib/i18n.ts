export type Key = keyof typeof DICT["en"];
export function translate(lang: string, key: Key, vars?: Record<string, string | number>) {
  let s = (DICT[lang] && DICT[lang][key]) || DICT.en[key] || String(key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
